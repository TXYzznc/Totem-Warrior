def main() -> None:
    for asset in ASSETS:
        for style_key in STYLE:
            write_brief(asset, style_key)
    print(f"Generated {len(ASSETS) * len(STYLE)} style briefs under {ROOT}")


if __name__ == "__main__":
    main()
